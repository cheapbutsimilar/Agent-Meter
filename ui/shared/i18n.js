  const nav = root.navigator || {};
  let lang = 'ko';

  /** The system language: Korean, or English for everything else. */
  function detect() {
    const l = (nav.languages && nav.languages[0]) || nav.language || '';
    return /^ko\b/i.test(l) ? 'ko' : 'en';
  }

  /** settings.language ('auto' | 'ko' | 'en') -> the language in use. */
  function setLang(pref) {
    lang = pref === 'ko' || pref === 'en' ? pref : detect();
    if (root.document) root.document.documentElement.lang = lang;
    return lang;
  }

  function t(key, vars) {
    const d = DICT[lang] || DICT.en;
    let s = key in d ? d[key] : key in DICT.ko ? DICT.ko[key] : key;
    if (typeof s === 'function') return s(vars || {});
    if (Array.isArray(s) || !vars) return s;
    return String(s).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  }

  /** A message from the collectors, in the current language. */
  function apiError(msg) {
    if (!msg || lang === 'ko') return msg;
    for (const [re, en] of API_ERRORS) if (en && re.test(msg)) return msg.replace(re, en);
    return msg;
  }

  /** Fill [data-i18n] (text), [data-i18n-html] and [data-i18n-title] (title + aria-label). */
  function applyDom(scope) {
    const el = scope || (root.document && root.document);
    if (!el) return;
    el.querySelectorAll('[data-i18n]').forEach((n) => (n.textContent = t(n.dataset.i18n)));
    el.querySelectorAll('[data-i18n-html]').forEach((n) => (n.innerHTML = t(n.dataset.i18nHtml)));
    el.querySelectorAll('[data-i18n-title]').forEach((n) => {
      const v = t(n.dataset.i18nTitle);
      n.title = v;
      n.setAttribute('aria-label', v);
    });
  }

